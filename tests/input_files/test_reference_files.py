"""Check the file formats against the reference files published by Ansys.

Round-trip tests cannot catch a mistake made symmetrically in the reader and in the
writer. The files in ``tests/assets/input_files`` were produced by Speos and attached to
the Ansys Optics knowledge base articles describing each format, so they pin the layout
independently from our own implementation:

* ``Non-Scattering.material``, ``Henyey-Greenstein.material``,
  ``Double Henyey-Greenstein.material``, ``Gegenbauer.material`` and
  ``User-Defined.material`` come from the Speos Scattering and Non-Scattering Volume
  Format articles.
* ``Coating Example.coated`` comes from the Speos Coating Surface Format article.
* ``KB.spectrum`` comes from the Create spectrum file from graph article.
* ``Gold.material`` and ``Birefringent SellMeier.material`` are the metallic and
  birefringent samples attached to the review of the file format support.
* the two ``*.OPT3DMapping`` files come from the ``3DTexture_Data.7z`` archive of the
  Homogeneous 3D Texture via Scripting article, and were generated by Speos itself.

Each test states what the article says the file holds, then checks that reading it gives
exactly that, and that writing the model back reproduces the original lines.
"""

